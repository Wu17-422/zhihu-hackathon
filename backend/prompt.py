# -*- coding: utf-8 -*-
"""
★ 提示词 —— 这是整个产品的灵魂 ★

P1 独占文件。别人不许改。
分析准不准、演示好不好看，90% 取决于这个文件。

调提示词的循环：
    改这里 → 跑 verify_zhida.py（或调 /api/analyze?force=live）
    → 看结果 → 再改

注意：每跑一次真接口 = 消耗 1 次额度（100 次/天）。
攒够几处改动再跑，别改一句跑一次。
"""

PROMPT_HEAD = """下面是一个知乎帖子下的 {n} 条评论。请完成两件事。

任务1（点出争论）：「core_dispute」——这个帖子下真正在争的是什么？一句话说清。
        后面每条评论的立场，都是相对这个问题而言的。
任务2（逐条分析）：对每一条评论，交付五样东西：
        stance  立场：只能是这三个值之一 —— agree / oppose / neutral，小写英文。
                指这条评论在 core_dispute 那个问题上的位置。
                没立场、纯表态、跑题、看不出来 → 一律 neutral。
        stance_detail  用一句话说清他的立场，给用户看的，比 stance 具体。
        gist    想表达什么：如果这条评论只允许说一句话，那句话是什么。
        logic   他的逻辑：把他的推理链拆出来（因为…所以…）。
                如果他根本没推理，就写「只是表态，没有论证」。
        flaws   逻辑漏洞：只在真的存在时写。每条格式「漏洞名：一句话说清漏洞在哪」，
                分隔符统一用全角「：」。没有就写空数组 []。
                常见类型参考：以偏概全、诉诸动机、稻草人、滑坡、把相关当因果、
                循环论证、无依据的数字、诉诸情绪、跑题。

硬性要求：
- 只依据评论内容，不要引入评论里没有的信息，不要编造数据
- flaws 宁缺毋滥（重要）：大部分评论就是正常表达经验或观点，根本没有漏洞。
  没有就写空数组 []。硬找漏洞比漏找更糟——演示时会被评委一眼看穿。
- stance、gist、logic 每项一句话，禁止展开成长段
- ids 必须是评论里出现的原始 id

只输出 JSON，不要任何解释文字、不要 markdown 代码块。格式如下：
"""

PROMPT_SCHEMA = """{
  "core_dispute": "一句话说清这个帖子下真正在争什么",
  "analyses": [
    {
      "id": 1,
      "stance": "agree 或 oppose 或 neutral（只能这三个，小写）",
      "stance_detail": "一句话说清他的立场",
      "gist": "他想表达什么，一句话",
      "logic": "他的推理链：因为…所以…；没论证就写「只是表态，没有论证」",
      "flaws": ["漏洞名：一句话说清漏洞在哪"]
    }
  ]
}"""


# ────────────────────────────────────────────────────────────
# 另一个入口：用户自己写了一条评论，发之前先帮他看逻辑
# ────────────────────────────────────────────────────────────

PROMPT_POLISH_HEAD = """用户准备在这个帖子下面发一条评论，发之前想让你先看一眼。

他的原话：
「{draft}」

请完成三件事。

任务1（概括观点）：他这段话到底在主张什么？一句话说清。
        概括的是他的意思，不是复述他的字。
任务2（挑漏洞）：这个主张在逻辑上站得住吗？
        站不住就指出具体问题。每条给出三样：
          name   漏洞名（以偏概全、诉诸动机、把相关当因果、论据不足……）
          claim  他话里出问题的那部分——概括它的意思，不必逐字抄
          why    一句话说清为什么这是漏洞
        宁缺毋滥（重要）：如果他写得没问题，flaws 就写空数组 []，
        并在 verdict 里直接肯定他。别为了显得有用硬找问题——那比漏找更让人反感。
任务3（搜索关键词）：给一组能在知乎上搜到「和他这条评论相关的讨论」的关键词。
        用途：拿它去搜知乎，把相关帖子推给他，让他发言前先看看别人怎么说的。
        要求：
        - 2~6 个词，空格分开，别写成一句话（搜索引擎吃关键词，不吃句子）
        - 抓他主张里的实体和争议点，别用「观点」「看法」「问题」这类没有信息量的词
        - 只用他话里出现的概念，不要引入新话题

注意：不要帮他改写评论。他要的是判断和参考资料，不是代笔。

只输出 JSON，不要任何解释文字、不要 markdown 代码块。格式如下：
"""

PROMPT_POLISH_SCHEMA = """{
  "viewpoint": "一句话概括他这段话在主张什么",
  "verdict": "一句话：这个主张的逻辑站不站得住",
  "flaws": [
    {"name": "漏洞名", "claim": "他话里出问题的那部分，概括其意思，不必逐字", "why": "为什么这是漏洞"}
  ],
  "topic": "搜索关键词 空格分开 2到6个"
}"""


def build_polish_prompt(draft):
    """draft: 用户自己写的评论原文"""
    return PROMPT_POLISH_HEAD.format(draft=draft) + PROMPT_POLISH_SCHEMA


def build_prompt(comments):
    """comments: [{"id": 1, "text": "..."}] —— id 已在 zhida.py 里重编成 1..N"""
    lines = [f'[{c["id"]}] {c["text"]}' for c in comments]
    return (
        PROMPT_HEAD.format(n=len(comments))
        + PROMPT_SCHEMA
        + "\n\n评论如下：\n"
        + "\n".join(lines)
    )


# ────────────────────────────────────────────────────────────
# 相关帖子推荐 —— 基于 core_dispute 搜索知乎上的相关讨论
# ────────────────────────────────────────────────────────────

PROMPT_RELATED = """你是一个知乎帖子推荐助手。已知用户在看一个帖子，帖子下争论的核心是：

「{dispute}」

请在知乎上搜索与这个争论相关的帖子，推荐 4-6 个值得用户点过去看看的帖子。
要求：
- 帖子的主题必须和上面这个核心争论直接相关
- 每个推荐给出：一个像知乎标题的帖子标题、一句话说清为什么跟当前讨论相关
- 不要编造帖子链接或 URL，只给标题和理由

只输出 JSON，不要任何解释文字、不要 markdown 代码块。格式如下：
"""

PROMPT_RELATED_SCHEMA = """{
  "related_posts": [
    {
      "title": "相关的知乎帖子标题",
      "reason": "为什么跟当前讨论有关，一句话"
    }
  ]
}"""


def build_related_prompt(dispute):
    """dispute: core_dispute 的内容"""
    return PROMPT_RELATED.format(dispute=dispute) + PROMPT_RELATED_SCHEMA


# ────────────────────────────────────────────────────────────
# 思维导图 —— 把帖子内容转成树状结构
# ────────────────────────────────────────────────────────────

PROMPT_MINDMAP = """你是一个知识结构化助手。请把下面这篇知乎回答/帖子的内容整理成思维导图。

要求：
- 用树状结构组织，根节点是文章的核心主题
- 往下分 2~3 层子节点，每层按逻辑分组（观点、论据、结论、举例等）
- 每个节点名称控制在 15 字以内，一句话概括
- 叶子节点 = 具体的论点、数据或事实
- 如果文章有多个对立观点，把它们分成不同的分支
- 不要遗漏文章的重要论点和论据
- 导图的层级总数控制在 3 层以内（根节点算第 1 层），避免太深

原文标题：{title}
原文内容：
{content}

只输出 JSON，不要任何解释文字、不要 markdown 代码块。格式如下：
"""

PROMPT_MINDMAP_SCHEMA = """{
  "mindmap": {
    "name": "核心主题（尽量用原文争议点，15字内）",
    "children": [
      {
        "name": "分支1：观点分组名",
        "children": [
          { "name": "具体论点1" },
          { "name": "具体论点2" }
        ]
      },
      {
        "name": "分支2",
        "children": [
          { "name": "论点" },
          {
            "name": "子分支",
            "children": [
              { "name": "细节点" },
              { "name": "细节点" }
            ]
          }
        ]
      }
    ]
  }
}"""


def build_mindmap_prompt(title, content):
    """title: 帖子标题, content: 正文内容"""
    return (
        PROMPT_MINDMAP.format(title=title, content=content)
        + PROMPT_MINDMAP_SCHEMA
    )


# ────────────────────────────────────────────────────────────
# 争议地图 —— 把 N 条评论压成几个阵营 + 分歧根源 + 被埋没的好评论
#
# 这是产品的首屏。和逐条分析的区别：
#   逐条分析 = 输入 800 条，输出 800 张卡片（比原文还长）
#   争议地图 = 输入 800 条，输出 5 个阵营（一屏看完）
# 压缩工具的产物必须比原料短，否则没有存在意义。
# ────────────────────────────────────────────────────────────

PROMPT_CAMPS = """下面是一个知乎帖子下的 {n} 条评论（该帖共 {total} 条，这里是按赞数和楼层抽样出来的代表）。
每条格式是：[编号] (赞 N, 第 M 楼) 评论内容

标题：{title}

请完成四件事。

任务1（争论焦点）「core_dispute」：这个帖子下真正在争的是什么？一句话。

任务2（划分阵营）「camps」：把这些评论归并成 3~5 个阵营。
        这是整个任务的核心 —— 几百条评论其实只有几种说法，你要找出那几种。
        每个阵营给出：
          name       阵营名，12 字以内，要能一眼看出立场（例：「AI 只是工具」）
          claim      这个阵营的核心主张，一句话
          stance     agree / oppose / neutral 三选一，小写。指该阵营在 core_dispute 上的位置
          grounds    这个阵营拿出来的论据，2~4 条，每条 15 字以内
          comment_ids 属于这个阵营的评论编号数组（用给你的编号）
          quote_id   这个阵营里最有代表性的那一条评论的编号（必须在 comment_ids 里）
        要求：
        - 阵营之间必须互相区分，不能是同一个意思换句话说
        - 每条评论只能归进一个阵营；实在归不了的不用勉强
        - 按阵营人数从多到少排

任务3（分歧根源）「crux」：双方其实卡在哪个具体判断上？
        不要写「一方认为A，一方认为B」这种废话，要指出他们真正的分歧点 ——
        往往是两拨人在用不同的标准，或者根本在谈不同的问题。两三句话说透。

任务4（被埋没的好评论）「buried_gems」：找出 1~3 条「赞数低、楼层靠后，但内容质量明显高于平均」的评论。
        这是给用户最大的价值：知乎的排序天然埋没晚来的好内容，你要把它捞出来。
        判断标准（同时满足才算）：
          - 赞数明显低于高赞评论（不要挑已经排在前面的）
          - 提供了别人没提供的东西：一手经验、具体数据、指出了讨论的盲点、真正回应了问题
        每条给出：
          id   评论编号
          why  为什么它值得被看到，一句话，要具体说它提供了什么别人没有的东西
        宁缺毋滥：如果确实没有这样的评论，写空数组 []。硬凑会被一眼看穿。

硬性要求：
- 只依据评论内容，不要引入评论里没有的信息，不要编造数据
- 编号必须是上面出现过的编号，不许编
- name / claim / grounds 每项都要短，这是给人一眼扫的，不是写文章

只输出 JSON，不要任何解释文字、不要 markdown 代码块。格式如下：
"""

PROMPT_CAMPS_SCHEMA = """{
  "core_dispute": "一句话说清这个帖子下真正在争什么",
  "crux": "两三句话说透双方真正卡在哪个判断上",
  "camps": [
    {
      "name": "阵营名，12字内",
      "claim": "这个阵营的核心主张，一句话",
      "stance": "agree 或 oppose 或 neutral",
      "grounds": ["论据1，15字内", "论据2，15字内"],
      "comment_ids": [1, 5, 9],
      "quote_id": 5
    }
  ],
  "buried_gems": [
    {"id": 23, "why": "为什么它值得被看到，具体说它提供了什么别人没有的"}
  ]
}"""


def build_camps_prompt(numbered, total, title=""):
    """
    numbered: [{"id": 1, "text": "...", "likes": N, "floor": M}] —— id 已重编成 1..N
    total:    该帖实际总评论数（可能远大于 len(numbered)，抽样过）
    """
    lines = [
        f'[{c["id"]}] (赞 {c.get("likes", 0)}, 第 {c.get("floor", c["id"])} 楼) {c["text"]}'
        for c in numbered
    ]
    return (
        PROMPT_CAMPS.format(
            n=len(numbered), total=total, title=title or "（没抓到标题）"
        )
        + PROMPT_CAMPS_SCHEMA
        + "\n\n评论如下：\n"
        + "\n".join(lines)
    )
